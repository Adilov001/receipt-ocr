"""List the lines of the full-text drafts that need a careful look on paper -> data/gt_drafts/REVIEW.md.

A draft is RapidOCR output of one photo (`_text_source` in data/gt/<id>.json), corrected by hand. Reading
every line is slow, and mistakes left in the draft are rewarded by the CER / WER metric, so this script
points at the lines where a mistake is likely:

* the recognizer was unsure of a word (confidence below --conf);
* Latin and Cyrillic letters mixed inside one word (e.g. "КАRТА");
* a lost Uzbek apostrophe ("ko chasi" for "koʻchasi", "To lov" for "Toʻlov");
* ERA receipts: an amount with 8/6/9 where the printer's dotted 0 is likely ("24 888.66");
* the same line twice in a row (a logo read as text, or a line read twice);
* text that another photo of the same receipt shows but the draft lacks (a missed line?).

It only reads; it never changes a label.
"""
import argparse
import json
import re
import sys
from pathlib import Path

from rapidfuzz import fuzz

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from receipt.config import ROOT, load_config  # noqa: E402
from receipt.dataset import load_meta  # noqa: E402
from receipt.pipeline import load_image, process  # noqa: E402

LAT = re.compile(r"[A-Za-z]")
CYR = re.compile(r"[А-Яа-яЁёЎўҚқҒғҲҳ]")
APOS = re.compile(r"\b(ko|to|bo|so|qo|yo|mo|go|o|g) (?=[a-zʻʼ'])", re.I)
DOTTED = re.compile(r"\d[.,][869]{2}\b|\b[869]{3}\b|\d[869]{3}[.,]")


def ocr(cfg, image):
    out = process(load_image(ROOT / cfg["data"]["images"] / image), cfg, engine="rapidocr",
                  cache_dir=ROOT / cfg["eval"]["cache_dir"])
    return out["lines"]


def best(line, ocr_lines):
    scored = [(fuzz.ratio(line.lower(), o["text"].lower()), o) for o in ocr_lines]
    return max(scored, key=lambda s: s[0], default=(0, None))


def reasons(line, prev, match, era, conf_min):
    out = []
    if match is not None:
        low = [w for w in match.get("words", []) if w["conf"] < conf_min]
        if low:
            out.append("OCR unsure: " + ", ".join(f"'{w['text']}' {w['conf']:.2f}" for w in low[:3]))
    if any(LAT.search(w) and CYR.search(w) for w in line.split()):
        out.append("Latin + Cyrillic letters in one word")
    if APOS.search(line):
        out.append("apostrophe lost? (oʻ / gʻ)")
    if era and DOTTED.search(line):
        out.append("0 read as 8/6/9? (dotted zero)")
    if prev is not None and line.strip() and line.strip().lower() == prev.strip().lower():
        out.append("same as the line above: logo or read twice? (logos are not text: keep one)")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--conf", type=float, default=0.90, help="word confidence below this is flagged")
    ap.add_argument("--out", default="data/gt_drafts/REVIEW.md")
    args = ap.parse_args()

    cfg = load_config()
    gt_dir, drafts = ROOT / cfg["data"]["gt"], ROOT / "data" / "gt_drafts"
    rows = load_meta(cfg)
    whole = {}
    for r in rows:
        if not ({"partial", "synthetic"} & set(r["conditions"])):
            whole.setdefault(r["receipt_id"], []).append(r)

    md = ["# Lines to check on paper", "",
          "Generated by `scripts/mark_doubtful.py`. Open the file named under each receipt, find the line",
          "number, compare with the paper and fix it if needed. Unmarked lines are probably fine, but still",
          "glance at the whole receipt once for lines the OCR missed completely.", ""]
    total = 0
    for j in sorted(gt_dir.glob("*.json")):
        gt = json.loads(j.read_text(encoding="utf-8"))
        src = gt.get("_text_source")
        if not src:
            continue
        rid = j.stem
        txt = gt_dir / f"{rid}.txt"
        where = "data/gt"
        if not txt.exists():
            txt, where = drafts / f"{rid}.txt", "data/gt_drafts"
        if not txt.exists():
            continue
        label = txt.read_text(encoding="utf-8").splitlines()
        seller = next((r["seller"] for r in whole.get(rid, [])), "")
        era = seller.startswith("era_")
        src_lines = ocr(cfg, src)

        flagged, prev = [], None
        for i, line in enumerate(label, 1):
            score, m = best(line, src_lines)
            why = reasons(line, prev, m if score >= 60 else None, era, args.conf)
            if why:
                flagged.append((i, line, "; ".join(why)))
            prev = line

        missing = []
        for r in whole.get(rid, []):
            if r["image"] == src:
                continue
            for o in ocr(cfg, r["image"]):
                t = o["text"].strip()
                if len(t) < 5 or o["conf"] < 0.9:
                    continue
                if max((fuzz.token_sort_ratio(t.lower(), x.lower()) for x in label), default=0) < 70 and all(
                        fuzz.token_sort_ratio(t.lower(), x.lower()) < 70 for x, _ in missing):
                    missing.append((t, r["image"]))

        total += len(flagged) + len(missing)
        md += [f"## {rid}  ({where}/{rid}.txt, drafted from {src}, {len(label)} lines)", ""]
        if not flagged and not missing:
            md += ["Nothing flagged.", ""]
            continue
        if flagged:
            md += ["| line | text | why |", "|---:|---|---|"]
            md += [f"| {i} | `{t.replace('|', '¦')}` | {w} |" for i, t, w in flagged]
            md.append("")
        if missing:
            md.append("Seen on another photo but not in the draft (missing line, or just read differently?):")
            md += [f"- `{t}` ({img})" for t, img in missing]
            md.append("")
        print(f"{rid}: {len(flagged)} lines, {len(missing)} maybe missing", flush=True)

    (ROOT / args.out).write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{total} marks -> {args.out}")


if __name__ == "__main__":
    main()
